// Read generated PNG alpha to compile deterministic navigation data. No image pixels are changed.
import {readFileSync,writeFileSync} from 'node:fs';
import {inflateSync} from 'node:zlib';
export function readPNG(path){
 const raw=readFileSync(path),chunks=[];let width,height,type;
 for(let at=8;at<raw.length;){const n=raw.readUInt32BE(at),tag=raw.toString('ascii',at+4,at+8),data=raw.subarray(at+8,at+8+n);if(tag==='IHDR'){width=data.readUInt32BE(0);height=data.readUInt32BE(4);type=data[9];if(data[8]!==8||data[12]!==0||![2,6].includes(type))throw Error('Unsupported PNG format');}if(tag==='IDAT')chunks.push(data);at+=n+12;}
 const bpp=type===6?4:3,bytes=inflateSync(Buffer.concat(chunks)),stride=width*bpp,pixels=new Uint8Array(height*stride);let offset=0;
 const paeth=(a,b,c)=>{const p=a+b-c,da=Math.abs(p-a),db=Math.abs(p-b),dc=Math.abs(p-c);return da<=db&&da<=dc?a:db<=dc?b:c;};
 for(let y=0;y<height;y++){const filter=bytes[offset++];for(let x=0;x<stride;x++){const a=x>=bpp?pixels[y*stride+x-bpp]:0,b=y?pixels[(y-1)*stride+x]:0,c=y&&x>=bpp?pixels[(y-1)*stride+x-bpp]:0;pixels[y*stride+x]=(bytes[offset++]+(filter===0?0:filter===1?a:filter===2?b:filter===3?Math.floor((a+b)/2):paeth(a,b,c)))&255;}}
 return {width,height,alpha:(x,y)=>x<0||y<0||x>=width||y>=height?0:type===6?pixels[(Math.floor(y)*width+Math.floor(x))*4+3]:255};
}
const image=readPNG('src/assets/reborn/cliffs.png');
const areas=[[0,0,.625,.53],[.625,0,.375,.53],[0,.53,.625,.47],[.625,.53,.375,.47]];
const frames=areas.map(([x,y,w,h])=>{
 const x0=Math.floor(x*image.width),y0=Math.floor(y*image.height),x1=Math.floor((x+w)*image.width),y1=Math.floor((y+h)*image.height);let left=x1,right=x0,top=y1,bottom=y0;
 for(let yy=y0;yy<y1;yy++)for(let xx=x0;xx<x1;xx++)if(image.alpha(xx,yy)>48){left=Math.min(left,xx);right=Math.max(right,xx);top=Math.min(top,yy);bottom=Math.max(bottom,yy);}
 return {x:left,y:top,w:right-left+1,h:bottom-top+1};
});
const code=readFileSync('src/reborn/world.ts','utf8'),literal=code.match(/const ROCKS = (\[[\s\S]*?\n\]);/)[1];
const groups=JSON.parse(literal.replace(/\/\/[^\n]*/g,'').replace(/,\s*]/g,']'));
const variants=[3,0,1,2,3,0,0,1,3,1,1,3,3,1,1],placements=[];
for(let id=0;id<groups.length;id++){
 const points=groups[id],left=Math.min(...points.map(p=>p[0]))*3,right=Math.max(...points.map(p=>p[0]))*3,top=Math.min(...points.map(p=>p[1]))*3,bottom=Math.max(...points.map(p=>p[1]))*3;
 const frame=frames[variants[id]],width=right-left,natural=width*frame.h/frame.w,count=bottom-top>natural*1.6?2:1;
 const height=count===2?(bottom-top)/1.75:Math.min(Math.max(natural,(bottom-top)*.7),(bottom-top)*1.2);
 for(let n=0;n<count;n++)placements.push({x:left,y:count===1?bottom-height:top+n*height*.75,w:width,h:height,frame:variants[id],region:id});
}
const solid=(x,y)=>{
 for(const p of placements){if(x<p.x||y<p.y||x>=p.x+p.w||y>=p.y+p.h)continue;const f=frames[p.frame];if(image.alpha(f.x+(x-p.x)/p.w*f.w,f.y+(y-p.y)/p.h*f.h)>80)return p.region;}
 return -1;
};
const grid=240,size=3762,cell=size/grid,blocked=new Uint8Array(grid*grid),cliffs=new Uint8Array(grid*grid),radius=cell/2+10;
for(let i=0;i<blocked.length;i++){
 const x=(i%grid+.5)*cell,y=(Math.floor(i/grid)+.5)*cell,region=solid(x,y);
 if(region>=0&&region<9)cliffs[i]=region+1;
 for(const dx of [-radius,0,radius])for(const dy of [-radius,0,radius])if(solid(x+dx,y+dy)>=0)blocked[i]=1;
}
const output=`// Generated by scripts/compile-terrain-art.mjs from the cliff atlas alpha.\nexport const TERRAIN_FRAMES=${JSON.stringify(frames)};\nexport const TERRAIN_PLACEMENTS=${JSON.stringify(placements)};\nexport const TERRAIN_BLOCKED='${Buffer.from(blocked).toString('base64')}';\nexport const TERRAIN_CLIFFS='${Buffer.from(cliffs).toString('base64')}';\n`;
writeFileSync('src/reborn/terrain-art.ts',output);
