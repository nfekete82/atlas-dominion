import {createServer} from 'node:http';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root=path.resolve(fileURLToPath(new URL('..',import.meta.url))),out=path.join(root,'src/assets/reborn/buildings-3d');
const args=process.argv.slice(2),kinds=args.filter(arg=>!arg.startsWith('--'));
await mkdir(out,{recursive:true});
const saveBuilding=async(name,data)=>{
 const target=path.join(out,name);await mkdir(path.dirname(target),{recursive:true});
 await writeFile(target,Array.isArray(data)?Buffer.from(data):name.endsWith('.png')?Buffer.from(data.split(',')[1],'base64'):data);
 if(name.endsWith('.json')){const meta=JSON.parse(data);console.log(meta.kind,meta.team,(meta.design?.parts??meta.parts)+' parts',meta.baker??'staged 3D assembly',meta.turret?'64 registered weapon views':meta.activity?'64 registered radar views':meta.stages?meta.stages+' assembly stages':'static body');}
};
const saveTurretRig=async data=>{
 const target=path.join(root,'src/reborn/turret-rig.ts'),previous=await readFile(target,'utf8').catch(()=>null);
 if(previous){
  const old=JSON.parse(previous.split('export const TURRET_RIG=')[1].split(' as const;')[0]);
  const flat=value=>Object.values(value).flatMap(v=>typeof v==='object'?flat(v):[v]),a=flat(old),b=flat(data);
  if(a.length===b.length&&a.every((v,i)=>Math.abs(v-b[i])<1e-10))return;
 }
 await writeFile(target,'// Generated by scripts/export-atlas-buildings.mjs turret. Coordinates normalized to visual width.\nexport const TURRET_RIG='+JSON.stringify(data)+' as const;\n');
};
if(args.includes('--cpu')){
 const {exportOfflineBuildings}=await import('./animation/offline-building-export.mjs');
 await exportOfflineBuildings({saveBuilding,saveTurretRig,constructionOnly:args.includes('--construction-only')},kinds);
}else{
 const {chromium}=await import('../tests/browser/node_modules/@playwright/test/index.mjs');
 const server=createServer(async(req,res)=>{try{const file=path.resolve(root,'.'+new URL(req.url,'http://localhost').pathname);if(!file.startsWith(root+path.sep))throw Error('Invalid asset path');res.setHeader('Content-Type',file.endsWith('.js')?'text/javascript':file.endsWith('.html')?'text/html':'application/octet-stream');res.end(await readFile(file));}catch{res.writeHead(404).end();}});
 let browser;
 try{
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve);});
  browser=await chromium.launch({channel:process.env.ATLAS_BROWSER_CHANNEL??'chrome',headless:true});
  const page=await browser.newPage();page.on('pageerror',e=>console.error(e));page.on('console',m=>{if(m.type()==='error')console.error(m.text());});
  await page.goto('http://127.0.0.1:'+server.address().port+'/scripts/animation/building-export.html'+(args.includes('--construction-only')?'?constructionOnly=1':''));await page.waitForFunction(()=>!!window.exportBuildings);
  await page.exposeFunction('saveTurretRig',saveTurretRig);await page.exposeFunction('saveBuilding',saveBuilding);
  await page.evaluate(kinds=>window.exportBuildings(kinds),kinds);
 }finally{await browser?.close();if(server.listening)await new Promise(resolve=>server.close(resolve));}
}
